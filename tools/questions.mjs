// Source of truth for every DFA on the site.
// Each entry: the exact language as a predicate `pred(w)`, the alphabet, and
// teaching content. tools/build.mjs turns the predicate into a minimal DFA,
// verifies it on every string up to a length bound, and writes assets/data/dfa-data.js.

const cnt = (w, c) => w.split(c).length - 1;
const lead = (w, c) => { let i = 0; while (i < w.length && w[i] === c) i++; return i; };
const trail = (w, c) => { let i = 0; while (i < w.length && w[w.length - 1 - i] === c) i++; return i; };
const sce = (s, c, e) => w => w.startsWith(s) && w.includes(c) && w.endsWith(e);

